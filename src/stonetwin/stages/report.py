"""Stage ``report``: merge metrics, regenerate ``docs/RESULTS.md``, figures and README block.

Every number written here is read from ``outputs/<scene>/*/stage.json`` (merged into
``outputs/<scene>/metrics.json``). Nothing is typed by hand. Figures are rendered from
pipeline outputs and contain no photographs of people; images are written without
EXIF.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import numpy as np
from PIL import Image

from stonetwin.stage import STAGE_DIRS, StageContext, StageError

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def merge_scene(scene_dir: Path) -> dict[str, Any]:
    """All ``stage.json`` records of one scene, keyed by stage name."""
    merged: dict[str, Any] = {}
    for stage, folder in STAGE_DIRS.items():
        p = scene_dir / folder / "stage.json"
        if p.is_file() and stage != "report":
            rec = json.loads(p.read_text(encoding="utf-8"))
            merged[stage] = {
                k: rec[k]
                for k in ("status", "finished_utc", "wall_clock_s", "params", "tools", "metrics")
                if k in rec
            }
    return merged


def f(v: Any, nd: int = 3) -> str:
    """Format a number for a table; ``—`` when missing."""
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        if v != 0 and (abs(v) < 10 ** (-nd) or abs(v) >= 1e5):
            return f"{v:.2e}"
        return f"{v:.{nd}f}"
    return str(v)


def get(d: dict, path: str) -> Any:
    """``get(m, "sfm.metrics.registered_fraction")``; None if any key is missing."""
    for k in path.split("."):
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


# --------------------------------------------------------------------------- figures
def _fig_recession(stones_json: Path, out: Path) -> bool:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.collections import PolyCollection

    if not stones_json.is_file():
        return False
    doc = json.loads(stones_json.read_text(encoding="utf-8"))
    st = [s for s in doc["stones"] if len(s["outline_wall"]) >= 3]
    vals = np.array([s["recession"] for s in st])
    lim = float(np.percentile(np.abs(vals), 98))
    fig, ax = plt.subplots(figsize=(10, 8), dpi=150)
    pc = PolyCollection(
        [np.asarray(s["outline_wall"]) for s in st],
        array=vals,
        cmap="RdBu",
        edgecolors="0.3",
        linewidths=0.2,
    )
    pc.set_clim(-lim, lim)
    ax.add_collection(pc)
    ax.autoscale()
    ax.set_aspect("equal")
    u = doc["units"] if doc["metric"] else "scene units"
    ax.set_xlabel(f"wall x ({u})")
    ax.set_ylabel(f"wall y ({u})")
    fig.colorbar(pc, ax=ax, shrink=0.7, label=f"recession ({u}); negative = set back")
    ax.set_title("Recession per stone (condition proxy, not a deterioration class)")
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    return True


def _fig_copy(src: Path, out: Path, width: int = 1600) -> bool:
    if not src.is_file():
        return False
    im = Image.open(src).convert("RGB")
    im.thumbnail((width, width))
    im.save(out, quality=88)  # new file: no EXIF
    return True


# --------------------------------------------------------------------------- text
def results_md(all_m: dict[str, dict], figs: dict[str, str]) -> str:
    """The full ``docs/RESULTS.md``."""
    L = [
        "# Results",
        "",
        "_Generated by `python -m stonetwin report` from `outputs/<scene>/metrics.json`. "
        "Do not edit by hand._",
        "",
    ]
    hw = all_m.get("highwall", {})
    metric = get(hw, "frame.metrics.metric")
    if metric is False:
        L += [
            "> **Relative units.** The capture contains no scale reference, so lengths "
            "and areas for `highwall` are in relative scene units (the wall region is "
            f"{f((get(hw, 'frame.metrics.wall_extent') or [None])[0], 1)} units wide). "
            "Ratios, counts, IoU and F1 are unitless and unaffected.",
            "",
        ]

    L += [
        "## Reconstruction",
        "",
        "| Scene | Images used | Registered | Mean reproj. error (px) "
        "| Sparse points | Splat PSNR (dB) | SSIM | LPIPS | Held-out views |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for sc, m in all_m.items():
        L.append(
            f"| `{sc}` | {f(get(m, 'sfm.metrics.n_images_input'))} | "
            f"{f(get(m, 'sfm.metrics.registered_fraction'))} | "
            f"{f(get(m, 'sfm.metrics.mean_reproj_error_px'))} | "
            f"{f(get(m, 'sfm.metrics.n_points3d'))} | {f(get(m, 'splat.metrics.psnr'), 2)} | "
            f"{f(get(m, 'splat.metrics.ssim'))} | {f(get(m, 'splat.metrics.lpips'))} | "
            f"{f(get(m, 'splat.metrics.n_test'))} |"
        )
    hold = get(hw, "splat.params.holdout_every")
    L += [
        "",
        f"Splat metrics are on held-out views only (1 image in {f(hold)} is never trained on).",
        "",
    ]
    if "dense" in hw:
        L += [
            f"Dense cloud (`highwall`, {get(hw, 'dense.params.backend_resolved')}): "
            f"{f(get(hw, 'dense.metrics.n_points'))} points; wall region "
            f"{f(get(hw, 'frame.metrics.n_points_wall'))} points; wall-plane inlier RMS "
            f"{f(get(hw, 'frame.metrics.inlier_rms'), 4)} scene units.",
            "",
        ]

    r = get(hw, "register.metrics")
    if r:
        ref = r["camera_reference"]
        L += [
            "## Registration of two independent half-reconstructions (`highwall`)",
            "",
            "One capture session split in two by capture order; each half reconstructed "
            "separately, then aligned by a similarity transform (FPFH + RANSAC, then "
            "point-to-plane ICP with joint scale). This tests the estimator, not change "
            "over time.",
            "",
            "| Quantity | Value |",
            "|---|---|",
            f"| Images per half (registered) | {r['subset_a']['n_registered']} / "
            f"{r['subset_b']['n_registered']} |",
            f"| Estimated scale | {f(r['scale'], 4)} |",
            f"| Rotation angle (deg) | {f(r['rotation_angle_deg'], 2)} |",
            f"| ICP converged, iterations | {f(r['icp_converged'])}, {f(r['icp_iterations'])} |",
            f"| Fitness | {f(r['fitness'])} |",
            f"| Inlier RMSE (scene units of half A) | {f(r['inlier_rmse'], 4)} |",
            f"| Cloud-to-cloud, overlap: median / 95th pct | {f(r['c2c_overlap']['median'], 4)}"
            f" / {f(r['c2c_overlap']['p95'], 4)} |",
            f"| Point spacing of half A (median NN) | {f(r['a_median_nn_spacing'], 4)} |",
            f"| vs. camera-pose reference: scale error | {f(100 * ref['scale_rel_error'], 2)} % |",
            f"| vs. camera-pose reference: rotation error (deg) | "
            f"{f(ref['rotation_error_deg'], 3)} |",
            f"| vs. camera-pose reference: translation error / scene size | "
            f"{f(100 * ref['translation_error_rel_extent'], 3)} % |",
            "",
        ]
        if "c2c" in figs:
            L += [
                f"![cloud-to-cloud]({figs['c2c']})",
                "",
                "The signed residual on the wall is a smooth bowl, not noise: each half "
                "calibrated its own lens distortion, which bends each reconstruction "
                "slightly differently. A similarity transform cannot absorb it.",
                "",
            ]

    s = get(hw, "segment.metrics")
    e = get(hw, "evaluate.metrics")
    if s:
        L += [
            "## Stone segmentation (`highwall`)",
            "",
            "| | ortho (baseline) | multiview (main) |",
            "|---|---|---|",
            f"| Stones found, whole wall | {f(get(s, 'ortho.n_stones'))} | "
            f"{f(get(s, 'multiview.n_stones'))} |",
            f"| Fraction of points labelled | {f(get(s, 'ortho.labelled_point_fraction'))} | "
            f"{f(get(s, 'multiview.labelled_point_fraction'))} |",
        ]
        if e:
            rows = [
                ("Ground-truth stones in region", "n_gt"),
                ("Predictions in region", "n_pred"),
                ("True positives", "tp"),
                ("Precision", "precision"),
                ("Recall", "recall"),
                ("**F1**", "f1"),
                ("Mean IoU of matched pairs", "mean_iou_matched"),
                ("Over-segmented GT stones", "over_segmented_gt"),
                ("Under-segmenting predictions", "under_segmenting_pred"),
            ]
            for label, k in rows:
                L.append(f"| {label} | {f(get(e, 'ortho.' + k))} | {f(get(e, 'multiview.' + k))} |")
            sweep = get(e, "multiview.f1_by_iou_threshold") or {}
            for t in [k for k in sweep if float(k) != e["iou_threshold"]]:
                L.append(
                    f"| F1 at IoU ≥ {t} (for information) | "
                    f"{f((get(e, 'ortho.f1_by_iou_threshold') or {}).get(t))} | "
                    f"{f((get(e, 'multiview.f1_by_iou_threshold') or {}).get(t))} |"
                )
            L += [
                "",
                f"Matching: Hungarian on IoU, true positive at IoU ≥ "
                f"{e['iou_threshold']}. Ground truth: {f(e['n_gt_in_region'])} stones drawn "
                f"by hand on the orthophoto; evaluation region {e['region']}.",
                "",
            ]
            ar = e.get("annotation_registration") or {}
            if "n_inliers" in ar:
                L += [
                    "The annotation was drawn on the orthophoto of an earlier run; it is "
                    "registered to this run's orthophoto by SIFT + RANSAC similarity "
                    f"({f(ar['n_inliers'])} inlier matches, residual "
                    f"{f(ar['rms_px_full_res'], 2)} px RMS, scale {f(ar['scale'], 4)}).",
                    "",
                ]
        if "eval" in figs:
            L += [
                f"![evaluation overlay]({figs['eval']})",
                "",
                "Green: ground truth. Cyan: matched predictions. Red: unmatched predictions. "
                "Orange: missed ground-truth stones.",
                "",
            ]

    a = get(hw, "attributes.metrics")
    if a:
        u = "scene units" if not a["metric"] else a["units"]
        L += [
            "## Per-stone attributes (`highwall`, multiview)",
            "",
            "`roughness_rms`, `recession` and `colour_delta_e` are **condition proxies**: "
            "geometric and colour measurements, not validated deterioration classes.",
            "",
            "| Quantity | Value |",
            "|---|---|",
            f"| Stones with records | {f(a['n_stones'])} |",
            f"| Median face area ({u}²) | {f(a['face_area_median'], 4)} |",
            f"| Median roughness RMS ({u}) | {f(a['roughness_rms_median'], 4)} |",
            f"| Median colour ΔE00 to wall median | {f(a['colour_delta_e_median'], 2)} |",
        ]
        cav = a.get("check_regions", {}).get("cavity")
        if cav:
            L += [
                f"| Open cavity: stones / median recession ({u}) | {f(cav['n_stones'])} / "
                f"{f(cav['recession_median_inside'], 4)} |",
                f"| Open cavity: fraction of stones set back | "
                f"{f(cav['recession_fraction_negative_inside'], 2)} |",
                f"| Rest of wall: median / 5th pct recession ({u}) | "
                f"{f(cav['recession_median_outside'], 4)} / {f(cav['recession_p05_outside'], 4)} |",
            ]
        L.append("")
        if "recession" in figs:
            L += [f"![recession]({figs['recession']})", ""]
    return "\n".join(L).rstrip() + "\n"


def readme_block(all_m: dict[str, dict]) -> str:
    """Short results table for the README."""
    hw = all_m.get("highwall", {})
    e, r, a = (
        get(hw, "evaluate.metrics"),
        get(hw, "register.metrics"),
        get(hw, "attributes.metrics"),
    )
    L = ["| Result | Value |", "|---|---|"]
    for sc in all_m:
        if get(all_m[sc], "splat.metrics.psnr") is not None:
            L.append(
                f"| `{sc}` splat, held-out PSNR / SSIM / LPIPS | "
                f"{f(get(all_m[sc], 'splat.metrics.psnr'), 2)} dB / "
                f"{f(get(all_m[sc], 'splat.metrics.ssim'))} / "
                f"{f(get(all_m[sc], 'splat.metrics.lpips'))} |"
            )
    if e:
        L.append(
            f"| Stone segmentation F1 at IoU ≥ {e['iou_threshold']}, multiview / ortho "
            f"({f(e['n_gt_in_region'])} hand-drawn stones) | "
            f"{f(get(e, 'multiview.f1'))} / {f(get(e, 'ortho.f1'))} |"
        )
    if r:
        L.append(
            f"| Half-to-half registration: scale error vs. camera reference | "
            f"{f(100 * r['camera_reference']['scale_rel_error'], 2)} % |"
        )
    if a and a.get("check_regions", {}).get("cavity"):
        L.append(
            f"| Open cavity stones set back (recession < 0) | "
            f"{f(a['check_regions']['cavity']['recession_fraction_negative_inside'], 2)} |"
        )
    metric = get(hw, "frame.metrics.metric")
    if metric is False:
        L += [
            "",
            "_Lengths are relative (scene units; the capture has no scale reference). Unitless "
            "results are unaffected._",
        ]
    return "\n".join(L)


def run(ctx: StageContext) -> None:
    """Merge metrics for every scene with outputs; regenerate RESULTS.md, figures, README."""
    out_root = ctx.root / "outputs"
    all_m: dict[str, dict] = {}
    for sd in sorted(p for p in out_root.iterdir() if p.is_dir() and (p / "01_sfm").is_dir()):
        m = merge_scene(sd)
        (sd / "metrics.json").write_text(json.dumps(m, indent=1), encoding="utf-8")
        all_m[sd.name] = m
    if ctx.scene not in all_m:
        raise StageError(f"no outputs for scene {ctx.scene}")
    # Main scene first.
    all_m = {ctx.scene: all_m[ctx.scene], **{k: v for k, v in all_m.items() if k != ctx.scene}}

    figdir = ctx.root / "docs" / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    sd = out_root / ctx.scene
    figs = {}
    if _fig_copy(sd / "05_register" / "c2c.png", figdir / f"{ctx.scene}_c2c.jpg"):
        figs["c2c"] = f"figures/{ctx.scene}_c2c.jpg"
    if _fig_copy(
        sd / "08_evaluate" / "overlays" / "multiview.png",
        figdir / f"{ctx.scene}_eval_multiview.jpg",
    ):
        figs["eval"] = f"figures/{ctx.scene}_eval_multiview.jpg"
    if _fig_recession(sd / "07_attributes" / "stones.json", figdir / f"{ctx.scene}_recession.png"):
        figs["recession"] = f"figures/{ctx.scene}_recession.png"

    (ctx.root / "docs" / "RESULTS.md").write_text(results_md(all_m, figs), encoding="utf-8")
    readme = ctx.root / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise StageError("README.md has no RESULTS:START/END markers")
    block = f"{START}\n{readme_block(all_m)}\n{END}"
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    readme.write_text(text, encoding="utf-8")
    ctx.inputs = {"scenes": list(all_m)}
    ctx.metrics = {"scenes": list(all_m), "figures": sorted(figs.values())}
