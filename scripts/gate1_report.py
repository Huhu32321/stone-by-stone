"""Assemble ``outputs/gate1.md`` from stage.json files and gate screenshots.

Not a pipeline stage. Every number is read from ``outputs/<scene>/*/stage.json``; the
prose sections (observations, joint visibility) are read from
``outputs/gate1_notes.md`` so that they can be written by a person after looking at the
pictures.

    python scripts/gate1_report.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
SCENES = ["highwall", "entrance"]


def _stage(scene: str, folder: str) -> dict | None:
    p = OUT / scene / folder / "stage.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def _fmt(v: object, nd: int = 3) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _splat_figure(scene: str, img_dir: Path) -> str | None:
    """Side-by-side held-out GT | render for the first test image."""
    s = _stage(scene, "03_splat")
    if not s:
        return None
    name = Path(s["metrics"]["test_images"][0]).stem
    test = OUT / scene / "03_splat" / "renders" / "test"
    gt, rd = Image.open(test / f"{name}_gt.png"), Image.open(test / f"{name}.png")
    w, h = gt.size
    pair = Image.new("RGB", (2 * w + 10, h), "white")
    pair.paste(gt, (0, 0))
    pair.paste(rd, (w + 10, 0))
    pair.thumbnail((1800, 1800))
    out = img_dir / f"splat_{scene}.jpg"
    pair.save(out, quality=88)  # PIL writes no EXIF unless asked
    return f"{out.relative_to(OUT).as_posix()}  (held-out view {name}: ground truth | render)"


def main() -> None:
    img_dir = OUT / "gate1_img"
    img_dir.mkdir(exist_ok=True)
    lines = ["# Gate 1 — reconstruction review", ""]
    lines += ["Generated by `scripts/gate1_report.py` from `stage.json` files.", ""]

    lines += ["## Structure from motion", ""]
    lines += [
        "| Scene | Images used | Registered | Fraction | Mean reproj. error (px) "
        "| 3D points | Mean track length |",
        "|---|---|---|---|---|---|---|",
    ]
    for sc in SCENES:
        s = _stage(sc, "01_sfm")
        if not s:
            continue
        m = s["metrics"]
        lines.append(
            f"| `{sc}` | {m['n_images_input']} | {m['n_images_registered']} | "
            f"{_fmt(m['registered_fraction'])} | {_fmt(m['mean_reproj_error_px'])} | "
            f"{m['n_points3d']} | {_fmt(m['mean_track_length'], 2)} |"
        )
    lines += ["", "Acceptance: registered fraction ≥ 0.90, mean reprojection error ≤ 1.0 px.", ""]

    lines += ["## Gaussian splat, held-out views only", ""]
    lines += [
        "| Scene | Train / test images | Iteration | PSNR (dB) | SSIM | LPIPS (VGG) "
        "| Gaussians | Render size |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for sc in SCENES:
        s = _stage(sc, "03_splat")
        if not s:
            lines.append(f"| `{sc}` | not run | | | | | | |")
            continue
        m = s["metrics"]
        lines.append(
            f"| `{sc}` | {m['n_train']} / {m['n_test']} | {m['eval_iteration']} | "
            f"{_fmt(m['psnr'], 2)} | {_fmt(m['ssim'])} | {_fmt(m['lpips'])} | "
            f"{m['n_gaussians']} | {m['render_resolution'][0]}×{m['render_resolution'][1]} |"
        )
    lines.append("")
    for sc in SCENES:
        fig = _splat_figure(sc, img_dir)
        if fig:
            lines += [f"![splat {sc}]({fig.split()[0]})", f"*{fig}*", ""]

    d = _stage("highwall", "02_dense")
    f = _stage("highwall", "04_frame")
    lines += ["## Dense cloud (`highwall`)", ""]
    if d:
        m = d["metrics"]
        lines += [
            f"- Backend: `{d['params']['backend_resolved']}`, "
            f"{d['params']['max_image_size']} px, fusion min views "
            f"{d['params']['fusion_min_num_pixels']}; {m['n_depth_maps']} depth maps; "
            f"{_fmt(d['wall_clock_s'] / 60, 1)} min.",
            f"- `dense.ply`: {m['n_points']} points, median nearest-neighbour spacing "
            f"{_fmt(m['median_nn_spacing'], 4)} scene units.",
        ]
    if f:
        m = f["metrics"]
        lines += [
            f"- `dense_wall.ply`: {m['n_points_wall']} points in the wall ROI; extent "
            f"{' × '.join(_fmt(v, 2) for v in m['wall_extent'])} {m['units']} units (x, y, z).",
            f"- Wall plane: inlier fraction {_fmt(m['inlier_fraction'])}, inlier RMS "
            f"{_fmt(m['inlier_rms'], 4)}. **metric: {str(m['metric']).lower()}** "
            f"(no `scale_refs.json` yet; scale = {m['scale']}).",
        ]
    lines.append("")
    gate = OUT / "highwall" / "gate1"
    for title, stem in [
        ("Overview", "dense_overview"),
        ("Close-up 1", "pair_closeup1"),
        ("Close-up 2", "pair_closeup2"),
        ("Cavity", "pair_cavity"),
    ]:
        src = gate / f"{stem}.png"
        if src.is_file():
            dst = img_dir / f"{stem}.png"
            shutil.copy2(src, dst)
            lines += [f"### {title}", "", f"![{title}]({dst.relative_to(OUT).as_posix()})", ""]
    shaded = gate / "dense_overview_shaded.png"
    if shaded.is_file():
        shutil.copy2(shaded, img_dir / shaded.name)
        lines += [
            "### Overview, geometry only (normal shading)",
            "",
            f"![shaded](gate1_img/{shaded.name})",
            "",
        ]
    lines += [
        "Close-ups and cavity: left = point colour, right = the same points shaded "
        "by their normals with grazing light from the upper left, so only geometry "
        "is shown.",
        "",
    ]

    notes = OUT / "gate1_notes.md"
    if notes.is_file():
        lines += [notes.read_text(encoding="utf-8").strip(), ""]
    (OUT / "gate1.md").write_text("\n".join(lines), encoding="utf-8")
    print(OUT / "gate1.md")


if __name__ == "__main__":
    main()
