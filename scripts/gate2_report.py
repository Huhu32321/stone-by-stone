"""Assemble ``outputs/gate2.md`` (segmentation review) from stage outputs.

Not a pipeline stage. Numbers come from ``06_segment/stage.json`` and from the label
rasters; prose comes from ``outputs/gate2_notes.md``. Run ``scripts/label_maps.py``
first.

    python scripts/gate2_report.py --window 330 1750 930 2350
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import open3d as o3d
from PIL import Image

from stonetwin.stages.segment import points_to_ortho_labels as raster_labels

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"


def _thumb(src: Path, dst: Path, width: int = 1600) -> str:
    im = Image.open(src).convert("RGB")
    im.thumbnail((width, width))
    im.save(dst, quality=88)  # no EXIF written
    return dst.relative_to(OUT).as_posix()


def window_count(lab: np.ndarray, box: tuple[int, int, int, int]) -> tuple[int, float]:
    """Labels with >= 50 % of their area inside ``box`` (x0, y0, x1, y1); labelled frac."""
    x0, y0, x1, y1 = box
    ids, tot = np.unique(lab[lab > 0], return_counts=True)
    total = dict(zip(ids.tolist(), tot.tolist(), strict=True))
    win = lab[y0:y1, x0:x1]
    wi, wc = np.unique(win[win > 0], return_counts=True)
    n = sum(1 for i, c in zip(wi.tolist(), wc.tolist(), strict=True) if c >= 0.5 * total[i])
    return n, float((win > 0).mean())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scene", default="highwall")
    ap.add_argument("--window", type=int, nargs=4, required=True, help="x0 y0 x1 y1 (px)")
    a = ap.parse_args()
    seg = OUT / a.scene / "06_segment"
    st = json.loads((seg / "stage.json").read_text(encoding="utf-8"))
    m = st["metrics"]
    img = OUT / "gate2_img"
    img.mkdir(exist_ok=True)

    meta = json.loads((seg / "ortho" / "ortho_meta.json").read_text(encoding="utf-8"))
    p = np.asarray(
        o3d.io.read_point_cloud(str(OUT / a.scene / "04_frame" / "dense_wall.ply")).points
    )
    box = tuple(a.window)
    counts = {}
    for meth in ("ortho", "multiview"):
        lab = raster_labels(p, np.load(seg / meth / "points_labels.npy"), meta)
        counts[meth] = window_count(lab, box)
    win_img = Image.open(seg / "ortho" / "ortho.png").crop(box)
    win_img.save(img / "count_window.jpg", quality=90)

    L = [
        "# Gate 2 — segmentation review",
        "",
        "Generated by `scripts/gate2_report.py`. Non-metric: areas and lengths are in scene units.",
        "",
    ]
    L += [
        "## Orthophoto",
        "",
        f"![ortho]({_thumb(seg / 'ortho' / 'ortho.png', img / 'ortho.jpg')})",
        "",
        f"{meta['width']} × {meta['height']} px, GSD {meta['gsd']} {meta['units']} units.",
        "",
    ]
    L += [
        "## Label maps, side by side (left: ortho, right: multiview)",
        "",
        f"![sbs]({_thumb(seg / 'methods_side_by_side.jpg', img / 'sbs.jpg', 2400)})",
        "",
    ]

    o, mv = m["ortho"], m["multiview"]
    L += [
        "## Stone counts",
        "",
        "| | ortho | multiview |",
        "|---|---|---|",
        f"| Stones (whole wall) | {o['n_stones']} | {mv['n_stones']} |",
        f"| Labelled fraction of points | {o['labelled_point_fraction']:.3f} | "
        f"{mv['labelled_point_fraction']:.3f} |",
        f"| SAM time (s) | {o['sam_seconds']} | {mv['sam_seconds']} |",
        f"| Stones in count window | {counts['ortho'][0]} | {counts['multiview'][0]} |",
        f"| Labelled fraction of window | {counts['ortho'][1]:.2f} | "
        f"{counts['multiview'][1]:.2f} |",
        "",
        f"ortho masks: {o['masks']}.  multiview: {mv['n_views']} views, "
        f"{mv['n_masks']} masks, {mv['n_edges']} edges, {mv['n_components']} components "
        f"({mv['n_components_multi_view']} seen in ≥ 2 views), "
        f"{mv['dropped_by_area']} dropped by area, at most {mv['max_masks_in_one_stone']} "
        "masks in one stone.",
        "",
        f"Count window: orthophoto pixels x {box[0]}–{box[2]}, y {box[1]}–{box[3]} "
        "(lower-left masonry).",
        "",
        "![window](gate2_img/count_window.jpg)",
        "",
    ]

    L += [
        "## Multi-view debug overlays",
        "",
        "Left: SAM masks in the photo. Right: final stone labels of the visible points.",
        "",
    ]
    for f in sorted((seg / "multiview" / "debug").glob("*.jpg"))[:5]:
        L += [f"![{f.stem}]({_thumb(f, img / ('mv_' + f.name))})", ""]

    notes = OUT / "gate2_notes.md"
    if notes.is_file():
        L += [notes.read_text(encoding="utf-8").strip(), ""]
    (OUT / "gate2.md").write_text("\n".join(L), encoding="utf-8")
    print(OUT / "gate2.md")


if __name__ == "__main__":
    main()
