"""Assemble ``outputs/gate3.md`` (release review). Not a pipeline stage.

Sections: final metrics (the README block written by ``report``, so the numbers are
the generated ones), the privacy checklist (output of ``scripts/privacy_check.py``),
repository size, and the limitations / notes from ``outputs/gate3_notes.md``.

    python scripts/gate3_report.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"


def _run(args: list[str]) -> str:
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True).stdout.strip()


def main() -> None:
    L = ["# Gate 3 — release review", "", "Generated by `scripts/gate3_report.py`.", ""]

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    m = re.search(r"<!-- RESULTS:START -->\n(.*?)\n<!-- RESULTS:END -->", readme, re.S)
    L += [
        "## Final metrics",
        "",
        "As generated into `README.md` by `python -m stonetwin "
        "report`; full tables in `docs/RESULTS.md`.",
        "",
        m.group(1) if m else "_missing_",
        "",
    ]

    run_log = OUT / "all_highwall_run.log"
    if run_log.is_file():
        lines = [
            x
            for x in run_log.read_text(encoding="utf-8", errors="ignore").splitlines()
            if x.startswith("[") or x.startswith("exit=")
        ]
        L += [
            "## End-to-end run",
            "",
            "`python -m stonetwin all --scene highwall --force`:",
            "",
            "```",
            *lines,
            "```",
            "",
        ]

    priv = _run([sys.executable, "scripts/privacy_check.py"])
    L += [
        "## Privacy checklist",
        "",
        "Automated (`scripts/privacy_check.py`):",
        "",
        "```",
        priv,
        "```",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| No GPS in committed or deployed files | "
        f"{'pass' if priv.endswith('PASS') else 'see above'} (raw photos carry none) |",
        f"| No camera serial numbers in committed files | "
        f"{'pass' if priv.endswith('PASS') else 'see above'} |",
        f"| No EXIF in committed images or the viewer build | "
        f"{'pass' if priv.endswith('PASS') else 'see above'} |",
        f"| Nothing from `docs/internal/` committed or quoted | "
        f"{'pass' if priv.endswith('PASS') else 'see above'} |",
        "| No identifiable people in committed or deployed files | checked by eye, see notes |",
        "",
    ]

    size = _run(["git", "count-objects", "-vH"])
    n_files = len(_run(["git", "ls-files"]).splitlines())
    big = _run(["git", "ls-files", "-s", "--", "viewer/public/data"])
    L += [
        "## Repository size",
        "",
        "```",
        size,
        "```",
        "",
        f"{n_files} tracked files. Viewer payload tracked under `viewer/public/data/`:",
        "",
        "```",
        "\n".join(
            f"{p}: {(ROOT / p).stat().st_size / 2**20:.1f} MB"
            for p in (ln.split("\t")[-1] for ln in big.splitlines())
        ),
        "```",
        "",
    ]

    notes = OUT / "gate3_notes.md"
    if notes.is_file():
        L += [notes.read_text(encoding="utf-8").strip(), ""]
    (OUT / "gate3.md").write_text("\n".join(L), encoding="utf-8")
    print(OUT / "gate3.md")


if __name__ == "__main__":
    main()
